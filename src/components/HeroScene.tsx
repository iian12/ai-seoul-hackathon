const VS = `attribute vec3 aPos; attribute vec3 aNor; attribute vec3 aCol; attribute vec3 aBar; attribute vec3 aMat;
uniform mat4 uMVP; uniform mat4 uLight; uniform float uRise;
varying vec3 vCol; varying vec3 vNor; varying vec3 vBar; varying vec4 vLight; varying vec3 vPos; varying vec3 vMat;
void main(){ vec3 p = aPos; p.y *= uRise; vCol = aCol; vNor = aNor; vBar = aBar; vMat = aMat; vLight = uLight * vec4(p, 1.0); vPos = p; gl_Position = uMVP * vec4(p, 1.0); }`
const FS = (edges: boolean) => `${edges ? '#extension GL_OES_standard_derivatives : enable\n' : ''}precision highp float;
uniform sampler2D uShadow; uniform vec3 uLightDir; uniform float uTexel;
varying vec3 vCol; varying vec3 vNor; varying vec3 vBar; varying vec4 vLight; varying vec3 vPos; varying vec3 vMat;
float unpack(vec4 c){ return dot(c, vec4(1.0, 1.0/255.0, 1.0/65025.0, 1.0/16581375.0)); }
${edges ? `float grid(float f){ float w = fwidth(f); return (1.0 - smoothstep(0.0, w * 1.2, abs(fract(f + 0.5) - 0.5))) * (1.0 - smoothstep(0.18, 0.4, w)); }` : ''}
void main(){
  vec3 n = normalize(vNor);
  float diff = max(dot(n, uLightDir), 0.0);
  vec3 lc = vLight.xyz * 0.5 + 0.5; float lit = 1.0;
  if (lc.x > 0.0 && lc.x < 1.0 && lc.y > 0.0 && lc.y < 1.0) {
    float bias = 0.0012 + 0.002 * (1.0 - diff); float s = 0.0;
    for (int i = -1; i <= 1; i++) for (int j = -1; j <= 1; j++) s += lc.z - bias > unpack(texture2D(uShadow, lc.xy + vec2(float(i), float(j)) * uTexel)) ? 0.0 : 1.0;
    lit = s / 9.0;
  }
  float sky = 0.5 + 0.5 * n.y;
  float ao = n.y > 0.9 ? 1.0 : mix(0.86, 1.0, clamp((vPos.y - 3.0) / 2.5, 0.0, 1.0));
  vec3 col = vCol * (0.70 + 0.12 * sky + 0.24 * diff * mix(0.42, 1.0, lit)) * ao;
  if (vMat.z < 0.0) col = vCol * (0.6 + 0.1 * sky + 0.4 * diff * mix(0.5, 1.0, lit)); // 산: 빛과 그늘을 더 또렷하게(지형 음영)
  ${edges ? `if (vMat.z > 0.0 && abs(n.y) < 0.35) {
    vec3 t = normalize(vec3(-n.z, 0.0, n.x)); float g = 0.0;
    if (vMat.x > 0.0) g = max(g, grid(vPos.y / vMat.x));
    if (vMat.y > 0.0) g = max(g, grid(dot(vPos, t) / vMat.y) * 0.75);
    col *= 1.0 - 0.2 * g * vMat.z;
  }
  vec3 d = fwidth(vBar); vec3 a = smoothstep(vec3(0.0), d * 0.9, vBar); float e = 1.0 - min(min(a.x, a.y), a.z); col = mix(col, vec3(0.42, 0.40, 0.36), e * 0.28);` : ''}
  gl_FragColor = vec4(col, 1.0);
}`

interface Props { picks: Recommendation[] | null; onFail: () => void }

const YAW0 = -0.38, PITCH0 = 0.86, INTRO = 2600, SPIN = (Math.PI * 2) / 150000 // 한 바퀴 2분 30초
