function footprints(): Foot[] {
  const f = UNIVERSITIES.map(u => { const A = u.area / (UNIT_M * UNIT_M), ab = A / 3.708; return { x: wx(u.lng), z: wz(u.lat), a: Math.sqrt(ab * u.asp), b: Math.sqrt(ab / u.asp), rot: u.rot } })
  for (let it = 0; it < 30; it++) for (let i = 0; i < f.length; i++) for (let j = i + 1; j < f.length; j++) {
    const p = f[i], q = f[j], dx = q.x - p.x, dz = q.z - p.z, d = Math.hypot(dx, dz) || .01
    const need = Math.sqrt(p.a * p.b) * 1.08 + Math.sqrt(q.a * q.b) * 1.08 + .5
    if (d < need) { const k = (need - d) / d / 2; p.x -= dx * k; p.z -= dz * k; q.x += dx * k; q.z += dz * k }
  }
  return f
}
const superRing = (f: Foot, scale = 1, n = 28): V2[] => Array.from({ length: n }, (_, i) => {
  const t = (i / n) * Math.PI * 2, c = Math.cos(t), s = Math.sin(t)
  const u = Math.sign(c) * Math.sqrt(Math.abs(c)) * f.a * scale, v = Math.sign(s) * Math.sqrt(Math.abs(s)) * f.b * scale
  return [f.x + u * Math.cos(f.rot) - v * Math.sin(f.rot), f.z + u * Math.sin(f.rot) + v * Math.cos(f.rot)]
})
const inFoot = (f: Foot, x: number, z: number, pad = 0) => {
  const dx = x - f.x, dz = z - f.z, c = Math.cos(f.rot), s = Math.sin(f.rot)
  const u = dx * c + dz * s, v = -dx * s + dz * c
  return (Math.abs(u) / (f.a + pad)) ** 4 + (Math.abs(v) / (f.b + pad)) ** 4 < 1
}

/** 대학 캠퍼스: 실제 면적 잔디 판 + 광장 + 상징 건물 + 강의동 + 가장자리 나무 */
function campus(m: Mesh, u: Uni, f: Foot, rand: () => number): number {
  const t = BASE + .16, B = C.brick, BD = C.brickDark, rot = f.rot
  const c = Math.cos(rot), s = Math.sin(rot), at = (uu: number, vv: number): V2 => [f.x + uu * c - vv * s, f.z + uu * s + vv * c]
  let maxY = t
  const track = (y: number) => { if (y > maxY) maxY = y }
  // 잔디 판
  slab(m, superRing(f), BASE, t, C.lawnSide, C.lawn)
  // 상징 건물 크기: 캠퍼스가 작을수록 함께 줄인다
  const sc = Math.max(.34, Math.min(1.1, Math.min(f.a, f.b) / 4.4)), hs = .5 + sc * .5
  const fl: V3 = [.5, 0, .38]
  const blk = (uu: number, vv: number, w: number, d: number, h: number, col = B, y0 = t) => { const [px, pz] = at(uu * sc, vv * sc); m.with(fl, () => box(m, px, pz, w * sc, d * sc, y0, y0 + h * hs, col, rot)); track(y0 + h * hs) }
  const roof = (uu: number, vv: number, w: number, d: number, y0: number, h: number, col = BD) => { const [px, pz] = at(uu * sc, vv * sc); gable(m, px, pz, w * sc, d * sc, y0, h * hs, col, rot); track(y0 + h * hs) }
  const spire = (uu: number, vv: number, r: number, y0: number, h: number, col = BD) => { const [px, pz] = at(uu * sc, vv * sc); cyl(m, px, pz, r * sc, 0, 4, y0, y0 + h * hs, col, null, Math.PI / 4 + rot); track(y0 + h * hs) }
  const Y = (h: number) => t + h * hs // 상징 건물의 높이 기준
  // 광장(포장)
  { const [px, pz] = at(0, f.b * .45); box(m, px, pz, f.a * .55, f.b * .32, t, t + .05, C.paving, rot, C.paving) }
  let reserve = 5.2 * sc // 상징 건물 자리(반지름)
  switch (u.style) {
    case 'gate': { // 서울대: 정문(ㅅ·ㄷ·ㅂ 조형) + 비탈을 따라 오르는 본부·도서관
      const [gx, gz] = at(0, f.b * .92)
      m.with([0, 0, 0], () => {
        box(m, gx - .55, gz, .3, .3, t, t + 3.2, BD, rot + .38); box(m, gx + .1, gz, .3, .3, t, t + 3.2, BD, rot - .38)
        box(m, gx + .9, gz, .26, .26, t, t + 2.4, BD, rot); box(m, gx + .9, gz, 1.1, .26, t + 1.5, t + 1.76, BD, rot); box(m, gx + .9, gz, 1.1, .26, t + 2.14, t + 2.4, BD, rot)
      })
      track(t + 3.2)
      blk(0, 0, 4.4, 2, 2.6); blk(0, 0, 1.6, 1.6, 4.6) // 본부
      blk(-3.6, -2.6, 3.4, 2.2, 3.4); blk(3.4, -2.8, 2.8, 2.4, 3.8) // 중앙도서관·관정관
      reserve = 5.6 * sc; break
    }
    case 'gothic': case 'stone': { // 연세대 언더우드관·고려대 본관: 중앙 탑이 있는 석조 본관 + 양 날개
      const st = u.style === 'stone' ? C.stone : B, tw = u.style === 'stone' ? 5 : 4.4
      blk(0, -.6, 6, 1.6, 2.2, st); roof(0, -.6, 6, 1.6, Y(2.2), 1.1)
      blk(-3.4, 1, 1.4, 3.6, 1.9, st); roof(-3.4, 1, 1.4, 3.6, Y(1.9), .9); blk(3.4, 1, 1.4, 3.6, 1.9, st); roof(3.4, 1, 1.4, 3.6, Y(1.9), .9)
      blk(0, -.6, 1.1, 1.1, tw, st); spire(0, -.6, .82, Y(tw), 1.8)
      if (u.style === 'stone') for (const uu of [-2.4, 2.4]) { blk(uu, -.6, .5, .5, 3, st); spire(uu, -.6, .38, Y(3), .9) }
      break
    }
    case 'hall': { // 경희대 평화의전당: 거대한 고딕 홀 + 쌍탑
      blk(0, -.4, 4.6, 3.4, 3.6, C.stone); roof(0, -.4, 4.6, 3.4, Y(3.6), 1.6)
      for (const uu of [-1.8, 1.8]) { blk(uu, 1.6, 1, 1, 6.2, C.stone); spire(uu, 1.6, .75, Y(6.2), 2.2) }
      break
    }
    case 'hanok': { // 성균관대 명륜당·동국대: 기단 위 전통 지붕
      blk(0, -.4, 4.4, 2.4, .5, C.paving); blk(0, -.4, 3.4, 1.6, 1.2, BD, Y(.5))
      { const [px, pz] = at(0, -.4 * sc); box(m, px, pz, 4.6 * sc, 2.8 * sc, Y(1.7), Y(2.9), C.tile, rot, C.tile, .45); track(Y(2.9)) }
      break
    }
    case 'valley': { // 이화여대 ECC: 땅을 가른 골짜기 양옆의 긴 매스 + 뒤쪽 석조관
      blk(-1.4, 0, 1.4, 5.6, .9, C.glass); blk(1.4, 0, 1.4, 5.6, .9, C.glass)
      blk(0, -4, 4.4, 1.4, 2.2); roof(0, -4, 4.4, 1.4, Y(2.2), 1); blk(0, -4, .9, .9, 3.6); spire(0, -4, .65, Y(3.6), 1.2)
      reserve = 5.8 * sc; break
    }
    case 'lake': { // 건국대 일감호·한국체대: 캠퍼스 넓이에 맞춘 호수
      const [px, pz] = at(-f.a * .12, -f.b * .05)
      slab(m, polyRing(px, pz, f.a * .42, f.b * .34, 18, rot).map(([x, z], i) => [x + Math.sin(i * 1.7) * .25, z + Math.cos(i * 2.3) * .25] as V2), t - .1, t + .02, C.acrylic, C.acrylic)
      blk(f.a * .55 / sc, -f.b * .2 / sc, 2.6, 1.6, 3.2) // 호숫가 본관
      reserve = Math.max(f.a, f.b) * .5; break
    }
    case 'tower': { // 한양대·중앙대·홍익대 등: 상징 고층관 + 저층 강의동
      blk(0, -.8, 4.2, 2.4, 1.6); blk(0, -.8, 1.8, 1.8, 8.8, B, Y(1.6)); blk(0, -.8, 1.3, 1.3, .6, BD, Y(10.4))
      break
    }
    default: { // 일반 캠퍼스: 광장을 둘러싼 본관
      blk(0, -1.2, 4.6, 1.3, 2.6); roof(0, -1.2, 4.6, 1.3, Y(2.6), .7)
      blk(-2.9, .4, 1.3, 3, 2); blk(2.9, .4, 1.3, 3, 3.2)
      reserve = 4 * sc
    }
  }
  // 강의동: 캠퍼스 축에 맞춘 격자에 듬성듬성(면적에 비례, 최대 46동)
  const occupied: [number, number, number, number][] = []
  const maxB = Math.max(1, Math.min(64, Math.round((f.a * f.b * 3.708) / 5)))
  const step = 2.5, cells: V2[] = []
  for (let uu = -f.a + 1; uu <= f.a - 1; uu += step) for (let vv = -f.b + 1; vv <= f.b - 1; vv += step) cells.push([uu + (rand() - .5) * .5, vv + (rand() - .5) * .5])
  cells.sort(() => rand() - .5)
  let placed = 0
  for (const [uu, vv] of cells) {
    if (placed >= maxB) break
    const w = 1.1 + rand() * 1.3, d = .8 + rand() * .8, h = 1 + rand() * 1.9
    const corners = [[-w / 2, -d / 2], [w / 2, -d / 2], [w / 2, d / 2], [-w / 2, d / 2]].map(([a, b]) => at(uu + a, vv + b))
    if (!corners.every(([x, z]) => inFoot(f, x, z, -.35))) continue
    if (Math.hypot(uu, vv) < reserve + 1) continue
    if (Math.abs(uu) < f.a * .3 + w / 2 && Math.abs(vv - f.b * .45) < f.b * .16 + d / 2) continue // 광장
    if (occupied.some(([a, b, ww, dd]) => Math.abs(a - uu) < (ww + w) / 2 + .4 && Math.abs(b - vv) < (dd + d) / 2 + .4)) continue
    occupied.push([uu, vv, w, d]); placed++
    const [px, pz] = at(uu, vv)
    m.with(fl, () => box(m, px, pz, w, d, t, t + h, rand() < .5 ? B : C.white, rot)); track(t + h)
    if (rand() < .35) gable(m, px, pz, w, d, t + h, .55, BD, rot)
    else if (rand() < .5) box(m, px + (rand() - .5) * w * .3, pz, w * .3, d * .4, t + h, t + h + .3, C.white, rot)
  }
  // 가장자리 나무 + 잔디 사이 나무
  const ring = superRing(f, .9, Math.max(8, Math.round((f.a + f.b) * 1.8)))
  ring.forEach(([x, z], i) => { if (i % 3 || rand() < .3) return; tree(m, x, z, t, .3 + rand() * .18, rand() < .4 ? C.treeDark : C.tree) })
  for (let i = 0, n = Math.round(f.a * f.b * .08); i < n; i++) {
    const uu = (rand() * 2 - 1) * f.a * .85, vv = (rand() * 2 - 1) * f.b * .85
    if (!inFoot(f, ...at(uu, vv), -.4) || Math.hypot(uu, vv) < reserve || occupied.some(([a, b, ww, dd]) => Math.abs(a - uu) < ww / 2 + .4 && Math.abs(b - vv) < dd / 2 + .4)) continue
    const [x, z] = at(uu, vv); tree(m, x, z, t, .26 + rand() * .16, rand() < .4 ? C.treeDark : C.tree)
  }
  return maxY
}

// ---------- 등고선 산(높이장 → 마칭 스퀘어) ----------
interface Terrain { G: Float32Array; F: Float32Array; R: Float32Array; gid: Int16Array; inside: Uint8Array; W: number; H: number; X0: number; Z0: number; S: number; pads: number[] }
/** 서울 전체 지형: 한강에서 멀어질수록 완만히 오르는 평지 + 낮은 구릉 + 실제 능선의 산을 부드럽게 합친다(해발 m → 단위).
 *  F: 숲 비율(산이 지배하는 곳), R: 한강까지 거리, pads: 건물·캠퍼스 자리를 그 자리 높이로 평평하게 고른 높이 */
function buildTerrain(rings: V2[][], ringGu: number[], pads: [number, number, number][]): Terrain {
  const S = .5, X0 = -180, Z0 = -150, W = Math.ceil(354 / S), H = Math.ceil(304 / S)
  const inside = new Uint8Array(W * H), gid = new Int16Array(W * H).fill(-1)
  rings.forEach((r, ri) => {
    const rows = new Map<number, number[]>()
    for (let i = 0; i < r.length; i++) {
      const [x1, z1] = r[i], [x2, z2] = r[(i + 1) % r.length]
      if (z1 === z2) continue
      const j0 = Math.ceil((Math.min(z1, z2) - Z0) / S), j1 = Math.floor((Math.max(z1, z2) - Z0) / S - 1e-9)
      for (let j = j0; j <= j1; j++) { const z = Z0 + j * S; if (!rows.has(j)) rows.set(j, []); rows.get(j)!.push(x1 + (x2 - x1) * (z - z1) / (z2 - z1)) }
    }
    rows.forEach((xs, j) => { if (j < 0 || j >= H) return; xs.sort((a, b) => a - b); for (let k = 0; k + 1 < xs.length; k += 2) for (let i = Math.max(0, Math.ceil((xs[k] - X0) / S)); i <= Math.min(W - 1, Math.floor((xs[k + 1] - X0) / S)); i++) { inside[j * W + i] = 1; gid[j * W + i] = ringGu[ri] } })
  })
  // 경계까지 거리(챔퍼)
  const D = new Float32Array(W * H)
  for (let k = 0; k < W * H; k++) D[k] = inside[k] ? 1e9 : 0
  for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) { const k = j * W + i; if (!D[k]) continue; if (i) D[k] = Math.min(D[k], D[k - 1] + 1); if (j) D[k] = Math.min(D[k], D[k - W] + 1); if (i && j) D[k] = Math.min(D[k], D[k - W - 1] + 1.41); if (j && i < W - 1) D[k] = Math.min(D[k], D[k - W + 1] + 1.41) }
  for (let j = H - 1; j >= 0; j--) for (let i = W - 1; i >= 0; i--) { const k = j * W + i; if (!D[k]) continue; if (i < W - 1) D[k] = Math.min(D[k], D[k + 1] + 1); if (j < H - 1) D[k] = Math.min(D[k], D[k + W] + 1); if (i < W - 1 && j < H - 1) D[k] = Math.min(D[k], D[k + W + 1] + 1.41); if (j < H - 1 && i) D[k] = Math.min(D[k], D[k + W - 1] + 1.41) }
  // 한강까지 거리
  const R = new Float32Array(W * H).fill(99)
  let rx0 = Infinity, rx1 = -Infinity, rz0 = Infinity, rz1 = -Infinity
  RIVER.forEach(([x, z]) => { rx0 = Math.min(rx0, x); rx1 = Math.max(rx1, x); rz0 = Math.min(rz0, z); rz1 = Math.max(rz1, z) })
  for (let j = Math.max(0, Math.floor((rz0 - 40 - Z0) / S)); j < Math.min(H, Math.ceil((rz1 + 40 - Z0) / S)); j++) for (let i = 0; i < W; i++) {
    const k = j * W + i; if (!inside[k]) continue
    const p: V2 = [X0 + i * S, Z0 + j * S]
    let d = 99; for (let n = 0; n < RIVER.length - 1; n++) { const a = RIVER[n]; if (Math.abs(a[0] - p[0]) > 45) continue; d = Math.min(d, segDist(p, a, RIVER[n + 1])) }
    R[k] = d
  }
  // 능선 조각(해발 m)
  const segs = RIDGES.flatMap(r => r.slice(0, -1).map((n0, i) => { const n1 = r[i + 1]; return { a: [wx(n0[0]), wz(n0[1])] as V2, b: [wx(n1[0]), wz(n1[1])] as V2, e0: n0[2], e1: n1[2], w0: n0[3] * R_WIDE, w1: n1[3] * R_WIDE } }))
  const reach = segs.map(g => { const w = Math.max(g.w0, g.w1) * 2.6; return { x0: Math.min(g.a[0], g.b[0]) - w, x1: Math.max(g.a[0], g.b[0]) + w, z0: Math.min(g.a[1], g.b[1]) - w, z1: Math.max(g.a[1], g.b[1]) + w } })
  const smax = (a: number, b: number, k: number) => { const dd = Math.abs(a - b); return Math.max(a, b) + (dd < k ? (k - dd) ** 2 / (4 * k) : 0) }
  const G = new Float32Array(W * H), F = new Float32Array(W * H)
  for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) {
    const k = j * W + i
    if (!inside[k]) continue
    const x = X0 + i * S, z = Z0 + j * S
    // 평지: 강가 6m → 강에서 멀어지며 40m 안팎, 낮은 구릉이 군데군데
    const base = 6 + 34 * smooth(1, 38, R[k] - RIVER_HALF) + 26 * Math.max(0, fbm(x * .045 + 3.1, z * .045 - 2.3) + .12)
    const qx = x + fbm(x * .09, z * .09) * 1.4, qz = z + fbm(x * .09 + 9.1, z * .09 - 3.7) * 1.4
    let ridge = 0
    for (let n = 0; n < segs.length; n++) {
      const r = reach[n]; if (qx < r.x0 || qx > r.x1 || qz < r.z0 || qz > r.z1) continue
      const g = segs[n], dx = g.b[0] - g.a[0], dz = g.b[1] - g.a[1], L2 = dx * dx + dz * dz || 1
      const t = Math.max(0, Math.min(1, ((qx - g.a[0]) * dx + (qz - g.a[1]) * dz) / L2)), ts = t * t * (3 - 2 * t)
      const d = Math.hypot(qx - g.a[0] - t * dx, qz - g.a[1] - t * dz), e = g.e0 + (g.e1 - g.e0) * ts, w = g.w0 + (g.w1 - g.w0) * t
      const q = d / w, v = e * (Math.exp(-q * q) * .9 + Math.exp(-q * 1.5) * .1)
      ridge = smax(ridge, v, 40)
    }
    ridge *= 1 + .07 * fbm(x * .25, z * .25)
    // 서울 경계: 평지는 넓게(12단위) 판 높이로 내려앉아 테두리 턱이 보이지 않게, 산은 짧게(5단위) — 경계에 걸친 산의 형태를 살린다
    const db = D[k] * S
    let tot = smax(base * smooth(0, 12, db), ridge * smooth(0, 5, db), 30) // 산자락이 평지로 스며들 듯 이어진다
    tot *= smooth(RIVER_HALF - .8, RIVER_HALF + 2.6, R[k]) // 강둑은 물가로 내려간다
    G[k] = toU(tot)
    F[k] = smooth(45, 150, ridge - base * .6) * smooth(RIVER_HALF + 1, RIVER_HALF + 4, R[k])
  }
  for (let pass = 0; pass < 2; pass++) {
    const BG = G.slice(), BF = F.slice()
    for (let j = 1; j < H - 1; j++) for (let i = 1; i < W - 1; i++) {
      const k = j * W + i
      if (!inside[k]) continue
      G[k] = (BG[k] * 4 + (BG[k - 1] + BG[k + 1] + BG[k - W] + BG[k + W]) * 2 + BG[k - W - 1] + BG[k - W + 1] + BG[k + W - 1] + BG[k + W + 1]) / 16
      F[k] = (BF[k] * 4 + (BF[k - 1] + BF[k + 1] + BF[k - W] + BF[k + W]) * 2 + BF[k - W - 1] + BF[k - W + 1] + BF[k + W - 1] + BF[k + W + 1]) / 16
    }
  }
  // 건물·캠퍼스 자리: 그 자리 높이로 평평하게 고르고, 둘레는 원래 땅으로 부드럽게
  const at = (x: number, z: number) => { const i = Math.round((x - X0) / S), j = Math.round((z - Z0) / S); return i < 0 || j < 0 || i >= W || j >= H ? 0 : G[j * W + i] }
  const padH = pads.map(([x, z, r]) => { let s2 = 0, n = 0; for (let a = 0; a < 8; a++) { s2 += at(x + Math.cos(a) * r * .5, z + Math.sin(a) * r * .5); n++ } return Math.min(s2 / n, at(x, z) + .6) })
  pads.forEach(([px, pz, r], pi) => {
    const tgt = padH[pi], ex = r + 2.8
    for (let j = Math.max(0, Math.floor((pz - ex - Z0) / S)); j <= Math.min(H - 1, Math.ceil((pz + ex - Z0) / S)); j++) for (let i = Math.max(0, Math.floor((px - ex - X0) / S)); i <= Math.min(W - 1, Math.ceil((px + ex - X0) / S)); i++) {
      const k = j * W + i; if (!inside[k]) continue
      const d = Math.hypot(X0 + i * S - px, Z0 + j * S - pz); if (d > ex) continue
      const t = smooth(r, ex, d); G[k] = tgt + (G[k] - tgt) * t; F[k] *= t
    }
  })
  return { G, F, R, gid, inside, W, H, X0, Z0, S, pads: padH }
}

interface Built { mesh: Mesh; anchors: V3[]; center: V3 }

interface Static { mesh: Mesh; anchors: V3[]; center: V3; terraceY: (x: number, z: number) => number }
let staticCache: Static | null = null
/** 핀만 바뀌면 산·건물은 다시 만들지 않는다(장면의 대부분은 고정) */
function buildScene(picks: Recommendation[]): Built {
  const st = staticCache ?? (staticCache = buildStatic())
  const m = new Mesh()
  m.pos = st.mesh.pos.slice(); m.nor = st.mesh.nor.slice(); m.col = st.mesh.col.slice(); m.bar = st.mesh.bar.slice(); m.mat = st.mesh.mat.slice()
  const top = BASE, anchors: V3[] = []
  // TOP 3 핀(주황·먹색 기둥 + 머리)
  picks.forEach((r, i) => {
    const x = wx(r.area.longitude), z = wz(r.area.latitude), col = i === 0 ? C.signal : C.ink, y0 = Math.max(top, st.terraceY(x, z))
    cyl(m, x, z, 1.4, 1.4, 16, y0, y0 + .25, col)
    cyl(m, x, z, .3, .3, 8, y0 + .25, y0 + 17, col, null)
    cyl(m, x, z, .01, 1.7, 12, y0 + 15.5, y0 + 18.4, col, null)
    dome(m, x, z, 1.7, 1.7, 1.6, y0 + 18.4, col, 12, 3)
    anchors.push([x, y0 + 21.5, z])
  })
  return { mesh: m, anchors: [...anchors, ...st.anchors], center: st.center }
}

