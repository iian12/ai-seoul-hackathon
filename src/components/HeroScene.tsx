// mat: [층선 간격, 멀리언 간격, 세기] — 셰이더가 세로 면에 층선과 창틀을 새긴다.
class Mesh {
  pos: number[] = []; nor: number[] = []; col: number[] = []; bar: number[] = []; mat: number[] = []
  cur: V3 = [0, 0, 0]
  get count() { return this.pos.length / 3 }
  with(mat: V3, fn: () => void) { const prev = this.cur; this.cur = mat; fn(); this.cur = prev }
  /** 삼각형. out이 주어지면 그 점에서 멀어지는 쪽으로 법선을 맞춘다. edges: 윤곽선을 그릴 변 */
  tri(a: V3, b: V3, c: V3, color: RGB, edges: Edges = ALL, out?: V3, up = false) {
    const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]]
    let n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
    const l = Math.hypot(n[0], n[1], n[2]) || 1; n = n.map(x => x / l)
    if (up) { if (n[1] < 0) n = n.map(x => -x) }
    else if (out) { const g = [(a[0] + b[0] + c[0]) / 3 - out[0], (a[1] + b[1] + c[1]) / 3 - out[1], (a[2] + b[2] + c[2]) / 3 - out[2]]; if (n[0] * g[0] + n[1] * g[1] + n[2] * g[2] < 0) n = n.map(x => -x) }
    // 윤곽선: 무게중심 좌표. 그리지 않을 변은 해당 좌표에 1을 더해 0에 닿지 않게 한다.
    const [ab, bc, ca] = edges
    const add = [bc ? 0 : 1, ca ? 0 : 1, ab ? 0 : 1]
    const bars: V3[] = [[1 + add[0], add[1], add[2]], [add[0], 1 + add[1], add[2]], [add[0], add[1], 1 + add[2]]]
    ;[a, b, c].forEach((p, i) => { this.pos.push(...p); this.nor.push(...n); this.col.push(...color); this.bar.push(...bars[i]); this.mat.push(...this.cur) })
  }
  /** 부드러운 삼각형: 꼭짓점마다 법선·색(산 지형용, 윤곽선 없음) */
  triV(p: V3[], n: V3[], c: RGB[]) {
    for (let i = 0; i < 3; i++) { this.pos.push(...p[i]); this.nor.push(...n[i]); this.col.push(...c[i]); this.bar.push(1, 1, 1); this.mat.push(0, 0, -1) }
  }
  /** 사각형(a-b-c-d 순서). 바깥 네 변만 윤곽선 */
  quad(a: V3, b: V3, c: V3, d: V3, color: RGB, out?: V3, edges: [boolean, boolean, boolean, boolean] = [true, true, true, true], up = false) {
    this.tri(a, b, c, color, [edges[0], edges[1], false], out, up)
    this.tri(a, c, d, color, [false, edges[2], edges[3]], out, up)
  }
}

/** 다각형 단면을 위로 쌓는 기둥(위쪽으로 좁아질 수 있음). ring: 바닥 단면(xz), scale: 위 단면 배율 */
function extrudeRing(m: Mesh, ring: V2[], y0: number, y1: number, side: RGB, top: RGB | null, scaleTop = 1, center?: V2, verticalEdges = true) {
  const cx = center ? center[0] : ring.reduce((s, p) => s + p[0], 0) / ring.length, cz = center ? center[1] : ring.reduce((s, p) => s + p[1], 0) / ring.length
  const topRing = ring.map(([x, z]) => [cx + (x - cx) * scaleTop, cz + (z - cz) * scaleTop] as V2)
  const out: V3 = [cx, (y0 + y1) / 2, cz]
  for (let i = 0; i < ring.length; i++) {
    const j = (i + 1) % ring.length
    m.quad([ring[i][0], y0, ring[i][1]], [ring[j][0], y0, ring[j][1]], [topRing[j][0], y1, topRing[j][1]], [topRing[i][0], y1, topRing[i][1]], side, out, [true, verticalEdges, true, verticalEdges])
  }
  if (top) {
    if (scaleTop === 0) return
    for (let i = 1; i < topRing.length - 1; i++) m.tri([topRing[0][0], y1, topRing[0][1]], [topRing[i][0], y1, topRing[i][1]], [topRing[i + 1][0], y1, topRing[i + 1][1]], top, [i === 1, true, i === topRing.length - 2], undefined, true)
  }
}
