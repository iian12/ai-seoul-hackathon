function dome(m: Mesh, cx: number, cz: number, rx: number, rz: number, h: number, y0: number, color: RGB, segs = 16, rings = 6) {
  const p = (i: number, k: number): V3 => { const a = (i / segs) * Math.PI * 2, t = (k / rings) * Math.PI / 2; return [cx + Math.cos(a) * Math.cos(t) * rx, y0 + Math.sin(t) * h, cz + Math.sin(a) * Math.cos(t) * rz] }
  const out: V3 = [cx, y0, cz]
  for (let k = 0; k < rings; k++) for (let i = 0; i < segs; i++) {
    const j = (i + 1) % segs
    if (k === rings - 1) m.tri(p(i, k), p(j, k), [cx, y0 + h, cz], color, [k === 0, false, false], out)
    else m.quad(p(i, k), p(j, k), p(j, k + 1), p(i, k + 1), color, out, [k === 0, false, false, false])
  }
}
