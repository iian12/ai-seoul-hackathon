const rectRing = (cx: number, cz: number, w: number, d: number, rot = 0): V2[] => { const c = Math.cos(rot), s = Math.sin(rot); return ([[-w / 2, -d / 2], [w / 2, -d / 2], [w / 2, d / 2], [-w / 2, d / 2]] as V2[]).map(([x, z]) => [cx + x * c - z * s, cz + x * s + z * c]) }
